#!/usr/bin/env python3
# Generates the OpenGL call table from Wine's dlls/opengl32/unixlib.h (Wine 11.0):
# src/opengl/funcs.rs (name and argument layout per unix call code) and ../../gl-funcs.js
# (the same names for the WebGL side). Usage: gen_opengl.py <path to unixlib.h>
import re, sys, os, json

here = os.path.dirname(os.path.abspath(__file__))
src = open(sys.argv[1]).read()

# one letter per argument kind: p pointer/handle (8), q 64-bit int, d double, f float,
# i int32, u uint32, s int16, H uint16, b int8, B uint8
KIND = {
    'GLdouble': 'd', 'GLclampd': 'd',
    'GLfloat': 'f', 'GLclampf': 'f', 'FLOAT': 'f',
    'GLint64': 'q', 'GLuint64': 'q', 'GLint64EXT': 'q', 'GLuint64EXT': 'q', 'GLintptr': 'q', 'GLsizeiptr': 'q',
    'GLintptrARB': 'q', 'GLsizeiptrARB': 'q', 'UINT64': 'q', 'GLvdpauSurfaceNV': 'q',
    'GLshort': 's', 'GLushort': 'H', 'GLhalfNV': 'H',
    'GLbyte': 'b', 'GLubyte': 'B', 'GLboolean': 'B', 'GLchar': 'b', 'GLcharARB': 'b',
    'GLenum': 'u', 'GLuint': 'u', 'GLbitfield': 'u', 'UINT': 'u', 'unsigned int': 'u', 'GLhandleARB': 'u',
    'GLint': 'i', 'GLsizei': 'i', 'int': 'i', 'BOOL': 'i', 'GLfixed': 'i', 'GLclampx': 'i',
}
POINTERS = {'HDC', 'HGLRC', 'HPBUFFERARB', 'PROC', 'LPCSTR', 'GLsync', 'GLeglImageOES', 'GLeglClientBufferEXT',
            'GLVULKANPROCNV', 'GLDEBUGPROC', 'GLDEBUGPROCARB', 'GLDEBUGPROCAMD', 'TEB'}
SIZE = {'p': 8, 'q': 8, 'd': 8, 'f': 4, 'i': 4, 'u': 4, 's': 2, 'H': 2, 'b': 1, 'B': 1}

structs = {}
for m in re.finditer(r'struct (\w+)_params\n\{\n(.*?)\n\};', src, re.S):
    fields = []
    for line in m.group(2).split('\n'):
        line = re.sub(r'/\*.*?\*/', '', line).strip().rstrip(';').strip()
        if not line or line.startswith('#') or line.startswith('/'):
            continue
        f = re.match(r'(.*?)\s*(\w+)(\[\d+\])?$', line)
        if not f:
            raise SystemExit('cannot read: ' + line)
        ty, name = f.group(1).strip(), f.group(2)
        if '*' in ty or ty.replace('const ', '') in POINTERS:
            k = 'p'
        elif ty.replace('const ', '') in KIND:
            k = KIND[ty.replace('const ', '')]
        else:
            k = None  # a struct by value: not callable through the table
        fields.append((name, k))
    structs[m.group(1)] = fields

names = re.search(r'enum unix_funcs\n\{\n(.*?)\n\};', src, re.S).group(1)
names = [n.strip().rstrip(',')[len('unix_'):] for n in names.split('\n') if n.strip().startswith('unix_')]

table = []
for n in names:
    fields = structs.get(n)
    if fields is None or any(k is None for _, k in fields):
        table.append((n, '!'))  # no plain layout (special call)
        continue
    sig, ret = '', ''
    for name, k in fields:
        if name == 'teb':
            continue
        if name == 'ret':
            ret = k
        else:
            sig += k
    table.append((n, sig + ('>' + ret if ret else '')))

with open(os.path.join(here, '..', 'src', 'opengl', 'funcs.rs'), 'w') as f:
    f.write('// Generated by tools/gen_opengl.py from Wine 11.0 dlls/opengl32/unixlib.h: do not edit.\n')
    f.write('// Each entry: (function name, argument kinds after the TEB pointer, ">" and the return kind).\n')
    f.write('// p pointer, q int64, d double, f float, i int32, u uint32, s int16, H uint16, b int8, B uint8; "!" = special.\n\n')
    f.write('pub static FUNCS: [(&str, &str); %d] = [\n' % len(table))
    for n, s in table:
        f.write('    ("%s", "%s"),\n' % (n, s))
    f.write('];\n')
with open(os.path.join(here, '..', '..', '..', 'gl-funcs.js'), 'w') as f:
    f.write('// Generated by src/engine/tools/gen_opengl.py from Wine 11.0 dlls/opengl32/unixlib.h: do not edit.\n')
    f.write('// The OpenGL unix call codes of Wine\'s opengl32.dll, by number.\n')
    f.write('self.GL_FUNCS = ' + json.dumps([n for n, _ in table]) + ';\n')
print(len(table), 'functions,', sum(1 for _, s in table if s == '!'), 'special')
