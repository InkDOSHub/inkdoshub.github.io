#!/usr/bin/env python3
"""Compact docs/graph/SUMMARY.md from graphify-out/graph.json (node-link JSON).

Goal: cheap context for agents. Map file -> most connected symbols (with line),
so a worker can open the right file/offset without reading code first.
Usage: graph-summary.py graphify-out/graph.json docs/graph/SUMMARY.md <commit>
"""
import json, sys, collections, datetime, re

src, out, commit = sys.argv[1], sys.argv[2], sys.argv[3]
name = sys.argv[4] if len(sys.argv) > 4 else "InkShell"
g = json.load(open(src))
nodes = g.get("nodes", [])
edges = g.get("links") or g.get("edges") or []

def f(n):
    return n.get("source_file") or n.get("file") or ""

def line(n):
    loc = str(n.get("source_location") or n.get("line") or "")
    m = re.search(r"\d+", loc)
    return m.group(0) if m else ""

byid = {n.get("id"): n for n in nodes}
deg = collections.Counter()
etype = collections.Counter()
for e in edges:
    s, t = e.get("source"), e.get("target")
    deg[s] += 1
    deg[t] += 1
    etype[e.get("relation") or e.get("type") or "?"] += 1

files = collections.defaultdict(list)
for n in nodes:
    if f(n):
        files[f(n)].append(n)

def label(n):
    return (n.get("label") or str(n.get("id")))[:60].replace("|", "\\|")

L = []
L.append(f"# Code graph summary: {name}\n")
L.append(f"Generated by graphify (AST, no LLM) via `.github/workflows/graph.yml` on "
         f"{datetime.date.today()}. Commit: `{commit}`. Raw graph not committed (CI artifact).\n")
L.append(f"- Nodes {len(nodes)}, edges {len(edges)}, files {len(files)}")
L.append("- Edge types: " + ", ".join(f"{k} {v}" for k, v in etype.most_common(8)) + "\n")
L.append("## Files (by symbols) -> top symbols `name:line(degree)`\n")
L.append("| File | Nodes | Top symbols |")
L.append("|---|---|---|")
for path, ns in sorted(files.items(), key=lambda kv: -len(kv[1]))[:40]:
    top = sorted(ns, key=lambda n: -deg[n.get("id")])[:6]
    syms = ", ".join(f"`{label(n)}:{line(n)}({deg[n.get('id')]})`" for n in top)
    L.append(f"| `{path}` | {len(ns)} | {syms} |")
L.append("\n## Most connected symbols\n")
L.append("| Symbol | File:line | Degree |")
L.append("|---|---|---|")
for nid, d in deg.most_common(25):
    n = byid.get(nid)
    if n:
        L.append(f"| `{label(n)}` | `{f(n)}:{line(n)}` | {d} |")
open(out, "w").write("\n".join(L) + "\n")
print(f"wrote {out}: {len(nodes)} nodes, {len(files)} files")
